#!/usr/bin/env python3
"""Snapshot this Mac into a setup folder. Usage: mac_setup.py sync [--dry-run]

Setup folder: $MAC_SETUP_DIR, else `setup_dir:` in ~/.config/mac-setup/config.yaml,
else ~/mac-setup. Needs a real macOS host (not a container or Cowork sandbox).
"""
import difflib, os, re, shutil, subprocess, sys
from pathlib import Path

HOME = Path.home()


def setup_dir():
    if os.environ.get("MAC_SETUP_DIR"):
        return Path(os.environ["MAC_SETUP_DIR"]).expanduser()
    cfg = HOME / ".config/mac-setup/config.yaml"
    if cfg.exists():
        m = re.search(r"^setup_dir:\s*[\"']?([^\"'#\n]+?)[\"']?\s*(#.*)?$", cfg.read_text(), re.M)
        if m:
            return Path(m.group(1)).expanduser()
    return HOME / "mac-setup"


OUT = setup_dir()
HERE = Path(__file__).resolve().parent
SECRET = re.compile(
    r"((api[_-]?key|secret|token|passw(or)?d|credential)\w*[\"']?\s*[=:]\s*[\"']?[A-Za-z0-9/+_.\-]{16,}"
    r"|(api[_-]?key|secret|token|passw(or)?d|credential)\w*</key>\s*<string>[^<]{16,}"
    r"|AKIA[0-9A-Z]{12,}|ghp_\w{20,}|sk-[\w-]{20,}|BEGIN [A-Z ]*PRIVATE KEY)", re.I)

DOTFILE_CANDIDATES = [".zshrc", ".zprofile", ".bashrc", ".bash_profile", ".gitconfig", ".gitignore_global",
                      ".vimrc", ".tmux.conf", ".p10k.zsh", ".config/starship.toml", ".config/ghostty/config",
                      ".config/git/ignore", ".config/karabiner/karabiner.json"]


def default_dotfiles():
    found = [f for f in DOTFILE_CANDIDATES if (HOME / f).is_file()]
    return "# paths relative to ~, one per line (seeded with the common ones that exist on this Mac)\n" + "".join(f + "\n" for f in found)


DEFAULT_DEFAULTS = """# domain key  (current value is read from this Mac on sync)
com.apple.dock autohide
com.apple.dock tilesize
com.apple.dock orientation
com.apple.dock show-recents
com.apple.finder AppleShowAllFiles
com.apple.finder ShowPathbar
com.apple.finder FXPreferredViewStyle
NSGlobalDomain AppleShowAllExtensions
NSGlobalDomain KeyRepeat
NSGlobalDomain InitialKeyRepeat
NSGlobalDomain ApplePressAndHoldEnabled
"""


def run(cmd):
    r = subprocess.run(cmd, capture_output=True, text=True)
    return r.stdout if r.returncode == 0 else ""


def brewfile():
    text = run(["brew", "bundle", "dump", "--file=-"])
    # mas reports id 0 for apps with no store receipt (e.g. old Bear); that line can never install
    return "".join(l for l in text.splitlines(True) if not re.search(r"^mas .*id: 0\s*$", l))


def npm_globals():
    out = run(["npm", "ls", "-g", "--depth=0", "--parseable"]).splitlines()[1:]
    return "".join(f"{Path(p).name if '@' not in p.split('node_modules/')[-1] else p.split('node_modules/')[-1]}\n"
                   for p in out if Path(p).name not in ("npm", "corepack"))


def defaults_script():
    lines = ["#!/bin/bash", "# Generated by mac-setup sync. Edit defaults.txt, not this file."]
    seen = set()
    for raw in (OUT / "defaults.txt").read_text().splitlines():
        if not raw.strip() or raw.startswith("#"):
            continue
        dom, key = raw.split()[:2]
        t = run(["defaults", "read-type", dom, key]).strip()
        v = run(["defaults", "read", dom, key]).strip()
        if not t or not v:
            continue
        flag = {"boolean": "-bool", "integer": "-int", "float": "-float", "string": "-string"}.get(t.split()[-1])
        if not flag:
            continue
        if flag == "-bool":
            v = "true" if v in ("1", "true") else "false"
        lines.append(f"defaults write {dom} {key} {flag} {v}")
        seen.add(dom.split(".")[-1])
    lines.append("killall Dock Finder 2>/dev/null || true")
    return "\n".join(lines) + "\n"


def slug(n):
    return re.sub(r"[^a-z0-9]+", "-", n.lower()).strip("-")


def cask_matches(apps):
    """Map app name -> cask token, verified against each candidate cask's .app artifact."""
    names = Path(run(["brew", "--cache"]).strip()) / "api/cask_names.txt"
    tokens = names.read_text().split() if names.exists() else []
    alnum = lambda x: re.sub(r"[^a-z0-9]", "", x.lower())
    cand = {}
    for app in apps:
        s, first = slug(app), slug(app).split("-")[0]
        hits = [t for t in tokens
                if t == s or first in t.split("-") or alnum(t).startswith(alnum(first)) and len(alnum(first)) >= 4
                or alnum(app).startswith(alnum(t)) and len(alnum(t)) >= 4]
        cand[app] = sorted(hits, key=lambda t: (t != s, len(t)))[:15]
    flat = sorted({t for v in cand.values() for t in v})
    if not flat:
        return {}
    import json
    try:
        casks = json.loads(run(["brew", "info", "--json=v2", "--cask"] + flat))["casks"]
    except ValueError:
        return {}
    by_app = {}
    for c in casks:
        blob = json.dumps(c.get("artifacts", []))
        for m in re.findall(r"/Applications/([^/\"]+)\.app", blob):
            by_app.setdefault(alnum(m), c["token"])
        for art in c.get("artifacts", []):
            for x in art.get("app", []) if isinstance(art, dict) else []:
                if isinstance(x, str):
                    by_app.setdefault(alnum(x.removesuffix(".app")), c["token"])
    return {a: by_app[alnum(a)] for a in apps if alnum(a) in by_app}


def unmanaged_apps(brew_text):
    installed = set(run(["brew", "list", "--cask"]).split())
    apps = []
    for p in sorted(Path("/Applications").glob("*.app")):
        if (p / "Contents/_MASReceipt").exists() or p.is_symlink():
            continue
        apps.append(p.stem)
    matches = cask_matches(apps)
    # apps already installed via a cask have no .app receipt; drop them
    apps = [a for a in apps if matches.get(a) not in installed]
    return apps, {a: matches[a] for a in apps if a in matches}


